package com.letustech.lab_sample_management_admin_backend.admin.exception;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.ExceptionHandler;
import org.springframework.web.bind.annotation.RestControllerAdvice;
import org.springframework.web.server.ResponseStatusException;

import java.util.HashMap;
import java.util.Map;

@RestControllerAdvice
public class AdminExceptionHandler {

    @ExceptionHandler(RuntimeException.class)
    public ResponseEntity<Map<String, String>> handleRuntimeException(
            RuntimeException exception
    ) {
        Map<String, String> response = new HashMap<>();
        response.put("message", exception.getMessage());

        HttpStatus status = HttpStatus.BAD_REQUEST;

        if ("Administrator is not logged in".equals(exception.getMessage())) {
            status = HttpStatus.UNAUTHORIZED;
        } else if ("Invalid username/email or password".equals(exception.getMessage())) {
            status = HttpStatus.UNAUTHORIZED;
        } else if ("Sample not found".equals(exception.getMessage())) {
            status = HttpStatus.NOT_FOUND;
        }

        return new ResponseEntity<>(response, status);
    }

    /**
     * Handles HTTP errors generated by ResponseStatusException.
     *
     * For example:
     * - Invalid sample status
     * - Invalid user ID
     *
     * This handler preserves the original HTTP status code
     * and returns a readable error message.
     */
    @ExceptionHandler(ResponseStatusException.class)
    public ResponseEntity<Map<String, String>>
    handleResponseStatusException(
            ResponseStatusException exception
    ) {

        // Create a response object containing the error message.
        Map<String, String> response = new HashMap<>();

        // getReason() returns the explanation supplied when
        // the exception was created.
        response.put(
                "message",
                exception.getReason() != null
                        ? exception.getReason()
                        : "Request failed"
        );

        // Preserve the original HTTP status, such as 400.
        return ResponseEntity
                .status(exception.getStatusCode())
                .body(response);
    }
}
